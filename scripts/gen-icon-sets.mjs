#!/usr/bin/env node
/**
 * 生成 `frontend/src/design/icon-sets.generated.ts`（Task 0016 · P2-S1）。
 *
 * ## 为什么要有这个脚本
 *
 * `icon-sets.tsx` 之前用**命名空间导入**（`import * as Tabler from "@tabler/icons-react"`）
 * + 动态索引（`bag[name]`）来支持"三套图标集可切换"。tree-shaking 对动态索引失效，
 * 于是三个库的**全部**图标进了首屏：phosphor 5069 KB + tabler 2667 KB + lucide 836 KB
 * = **8572 KB**（主 chunk 9.27 MB 的 87%–92%），而我们只用了 41 个语义名。
 *
 * 实测对照（同一 41 × 3）：改命名导入后 **136 KB min / 33 KB gzip**。
 *
 * ## 做什么
 *
 * 读两张事实表（都是人工维护的唯一来源）：
 *  - `icons.tsx` 的 `ICONS`：语义名 → **tabler 组件名**（`IconXxx`）
 *  - `icon-sets.tsx` 的 `LUCIDE_MAP` / `PHOSPHOR_MAP`：语义名 → **字符串名**（`null` = 该套缺此项）
 *
 * 产出 123 个具名 import + 三个静态对象。生成文件禁手改（改 map 后重跑本脚本）。
 *
 * ## 幂等
 *
 * 输出按语义名排序（不跟 map 的书写顺序），所以同样的输入永远产出同样的文件。
 * `pnpm lint:icons` 会做一致性检查：源表改了却没重跑 → 红。
 *
 * 用法：`pnpm gen:icons`（`--check` 只校验不写，供门禁调用）
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const ICONS_TSX = join(ROOT, "frontend/src/design/icons.tsx");
const SETS_TSX = join(ROOT, "frontend/src/design/icon-sets.tsx");
const OUT_TS = join(ROOT, "frontend/src/design/icon-sets.generated.ts");

/** 解析 `ICONS = { "kebab-name": IconPascal, … }` → `[[name, "IconPascal"], …]` */
function parseIcons(source) {
  const block = source.slice(source.indexOf("export const ICONS = {"));
  const body = block.slice(0, block.indexOf("} as const;"));
  const out = [];
  for (const line of body.split("\n")) {
    const m = /^\s*"?([\w-]+)"?:\s*(Icon\w+),/.exec(line);
    if (m) out.push([m[1], m[2]]);
  }
  return out;
}

/** 解析 `const XXX_MAP: Record<IconName, string | null> = { "k": "Name", … };` */
function parseMap(source, mapName) {
  const marker = `const ${mapName}: Record<IconName, string | null> = {`;
  const at = source.indexOf(marker);
  if (at === -1) throw new Error(`找不到 ${mapName}（源表结构变了？）`);
  const body = source.slice(at + marker.length, source.indexOf("};", at));
  const out = [];
  for (const line of body.split("\n")) {
    const m = /^\s*"?([\w-]+)"?:\s*(null|"[\w]+"),/.exec(line);
    if (m) out.push([m[1], m[2] === "null" ? null : m[2].slice(1, -1)]);
  }
  return out;
}

const iconsSource = readFileSync(ICONS_TSX, "utf8");
const setsSource = readFileSync(SETS_TSX, "utf8");

const tabler = parseIcons(iconsSource);
const lucide = parseMap(setsSource, "LUCIDE_MAP");
const phosphor = parseMap(setsSource, "PHOSPHOR_MAP");

if (tabler.length === 0) throw new Error("解析不出 ICONS（源表结构变了？）");
if (lucide.length !== tabler.length || phosphor.length !== tabler.length) {
  throw new Error(`三套语义名数量不一致：tabler ${tabler.length} / lucide ${lucide.length} / phosphor ${phosphor.length}`);
}

const names = tabler.map(([name]) => name).sort();
const byName = new Map(tabler.map(([n, c]) => [n, c]));
const lucideByName = new Map(lucide);
const phosphorByName = new Map(phosphor);

/** 生成 import 语句：同名的多个别名要区分（lucide 的 X 与 phosphor 的 X 会撞）。 */
function importBlock(pkgPrefix, entries) {
  const lines = entries.map(([alias, spec]) => `  ${spec} as ${alias},`);
  return `import {\n${[...new Set(lines)].sort().join("\n")}\n} from "${pkgPrefix}";`;
}

const tablerAlias = (name) => `T_${byName.get(name)}`;
const lucideAlias = (name) => {
  const spec = lucideByName.get(name);
  return spec === null || spec === undefined ? null : `L_${spec}`;
};
const phosphorAlias = (name) => {
  const spec = phosphorByName.get(name);
  return spec === null || spec === undefined ? null : `P_${spec}`;
};

/** 同一个组件名可能在两套里都出现（如 X）——别名前缀天然不撞，但 import 侧要去重。 */
function uniqImports(pairs) {
  const seen = new Map();
  for (const [alias, spec] of pairs) if (!seen.has(spec)) seen.set(spec, alias);
  return [...seen.entries()].map(([spec, alias]) => [alias, spec]);
}

const tablerImports = uniqImports(names.map((n) => [tablerAlias(n), byName.get(n)]));
const lucideImports = uniqImports(names.flatMap((n) => { const a = lucideAlias(n); return a === null ? [] : [[a, lucideByName.get(n)]]; }));
const phosphorImports = uniqImports(names.flatMap((n) => { const a = phosphorAlias(n); return a === null ? [] : [[a, phosphorByName.get(n)]]; }));

const entriesOf = (aliasOf) => names.map((n) => {
  const a = aliasOf(n);
  return `  "${n}": ${a ?? "null"},`;
}).join("\n");

const output = `// @generated by scripts/gen-icon-sets.mjs —— 不要手改。
//
// 源表（人工维护的唯一来源）：
//   · frontend/src/design/icons.tsx 的 ICONS（语义名 → tabler 组件）
//   · frontend/src/design/icon-sets.tsx 的 LUCIDE_MAP / PHOSPHOR_MAP（语义名 → 字符串名）
// 改了源表就重跑 \`pnpm gen:icons\`；\`pnpm lint:icons\` 会检查两者是否一致。
//
// 为什么生成静态对象而不是 \`import * as\` + \`bag[name]\`（Task 0016 · P2-S1）：
// 动态索引让 tree-shaking 失效，三个库整包进首屏（实测 8572 KB / 主 chunk 的 ≈87%–92%），
// 而我们只用 41 个语义名。命名导入后实测 136 KB min / 33 KB gzip。

import type { ComponentType } from "react";
import {
${tablerImports.map(([alias, spec]) => `  ${spec} as ${alias},`).join("\n")}
} from "@tabler/icons-react";
import {
${lucideImports.map(([alias, spec]) => `  ${spec} as ${alias},`).join("\n")}
} from "lucide-react";
import {
${phosphorImports.map(([alias, spec]) => `  ${spec} as ${alias},`).join("\n")}
} from "@phosphor-icons/react";

/** 三套图标库的组件签名不完全一致（size 类型、strokeWidth 有无），对外统一成这个窄类型。 */
export type IconComponent = ComponentType<Record<string, unknown>>;

export const TABLER_ICONS: Record<string, IconComponent | null> = {
${entriesOf(tablerAlias)}
};

export const LUCIDE_ICONS: Record<string, IconComponent | null> = {
${entriesOf(lucideAlias)}
};

export const PHOSPHOR_ICONS: Record<string, IconComponent | null> = {
${entriesOf(phosphorAlias)}
};
`;

const check = process.argv.includes("--check");
const previous = (() => { try { return readFileSync(OUT_TS, "utf8"); } catch { return ""; } })();

if (check) {
  if (previous !== output) {
    console.error("icon-sets.generated.ts 与源表不一致——请运行 `pnpm gen:icons` 后重新提交。");
    process.exit(1);
  }
  console.log(`icon-sets.generated.ts 已是最新（${names.length} 个语义名 × 3 套）。`);
} else {
  writeFileSync(OUT_TS, output);
  console.log(`已生成 ${OUT_TS}`);
  console.log(`语义名 ${names.length} 个：tabler ${tablerImports.length} / lucide ${lucideImports.length} / phosphor ${phosphorImports.length} 个具名 import`);
}
